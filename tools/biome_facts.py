"""Extracts verified biome and ore facts from the Minecraft jar into docs/biomes-and-heights.md.

Usage (after a Gradle build, so Loom has downloaded the game):
    python tools/biome_facts.py [--jar <minecraft-common jar>]

The biome texts in tools/make_lang.py and the numbers in OreTable.java are checked against this output.
"""
import argparse
import json
import re
import zipfile
from collections import defaultdict

from mcjar import ROOT, find_jar

FOOD_ANIMALS = {"cow", "pig", "sheep", "chicken", "rabbit", "mooshroom", "goat", "camel", "llama"}
NOTABLE_MONSTERS = {"husk", "stray", "bogged", "drowned", "witch", "slime", "creaking", "sulfur_cube", "parched",
                    "zombified_piglin", "piglin", "hoglin", "ghast", "magma_cube", "blaze", "enderman", "wither_skeleton"}
ORE_FEATURES = {"ore_gold_extra": "extra gold (Y 32..256)", "ore_emerald": "emerald", "ore_copper_large": "large copper veins"}


def height(a):
    if "absolute" in a:
        return a["absolute"]
    if "above_bottom" in a:
        return -64 + a["above_bottom"]
    if "below_top" in a:
        return 320 - a["below_top"]
    return a


def biome_rows(z):
    rows = []
    for name in sorted(n for n in z.namelist() if n.startswith("data/minecraft/worldgen/biome/") and n.endswith(".json")):
        d = json.loads(z.read(name))
        bid = name.split("/")[-1][:-5]
        spawns = d.get("attributes", {}).get("minecraft:gameplay/natural_mob_spawns", {}).get("argument", {}).get("spawns_by_category", {})
        mobs = defaultdict(set)
        for cat, entries in spawns.items():
            for e in entries:
                mobs[cat].add(e["type"].split(":")[1])
        feats = {f.split(":")[1] for step in d.get("features", []) for f in (step if isinstance(step, list) else [step]) if isinstance(f, str)}
        rows.append({
            "id": bid,
            "temperature": d.get("temperature"),
            "food": sorted(mobs["creature"] & FOOD_ANIMALS),
            "creatures": sorted(mobs["creature"]),
            "monsters": sorted(mobs["monster"]),
            "notable": sorted(mobs["monster"] & NOTABLE_MONSTERS),
            "ores": [label for key, label in ORE_FEATURES.items() if key in feats],
        })
    return rows


def ore_rows(z):
    out = []
    for name in sorted(n for n in z.namelist() if re.match(r"data/minecraft/worldgen/placed_feature/ore_(coal|iron|copper|gold|redstone|lapis|diamond|emerald)", n)):
        d = json.loads(z.read(name))
        parts = []
        for m in d["placement"]:
            t = m["type"].split(":")[1]
            if t == "height_range":
                h = m["height"]
                parts.append(f"{h['type'].split(':')[1]} {height(h['min_inclusive'])}..{height(h['max_inclusive'])}")
            elif t == "count":
                parts.append(f"count {m['count'] if isinstance(m['count'], int) else 'variable'}")
            elif t == "rarity_filter":
                parts.append(f"1/{m['chance']} chunks")
        out.append((name.split("/")[-1][:-5], "; ".join(parts)))
    return out


def main():
    parser = argparse.ArgumentParser(description="Write docs/biomes-and-heights.md from the Minecraft jar.")
    parser.add_argument("--jar", help="minecraft-common jar (default: the one in the Loom cache)")
    jar = find_jar(parser.parse_args().jar)
    with zipfile.ZipFile(jar) as z:
        write(z, jar.parent.name)


def write(z, version):
    lines = [f"# Biomes and heights (Minecraft {version})", "",
             "*Generated by `tools/biome_facts.py` from the game files. Do not edit by hand.*", "",
             "## Ores by height", "", "| Feature | Placement |", "|---|---|"]
    lines += [f"| `{n}` | {p} |" for n, p in ore_rows(z)]
    lines += ["", "Trapezoid = most ore in the middle of the range. Ranges outside the world (−64…320) are clipped.", "",
              "## Biomes", "", "| Biome | Temp | Food animals | Notable monsters | Extra ores |", "|---|---|---|---|---|"]
    for r in biome_rows(z):
        lines.append(f"| `{r['id']}` | {r['temperature']} | {', '.join(r['food']) or '—'} | {', '.join(r['notable']) or '—'} | {', '.join(r['ores']) or '—'} |")

    with open(ROOT / "docs" / "biomes-and-heights.md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote docs/biomes-and-heights.md from {version} ({len(biome_rows(z))} biomes)")


if __name__ == "__main__":
    main()
